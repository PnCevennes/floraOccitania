    <h1 class="m-3 text-center">Flors de Cevenas</h1>
    <div>
      <p>
        La langue occitane est un vecteur privilégié de transmission des savoirs
        et savoir-faire concernant le patrimoine naturel et l’usage des plantes.
        Afin de conserver les connaissances locales dans ce domaine, il est
        apparu indispensable d’intégrer aux inventaires naturalistes du parc
        national des Cévennes une traduction des dénominations en occitan,
        associée aux usages des plantes.
      </p>
      <p>
        Ce travail de recherche confié à l’ethnologue Monique Carlier en
        2019-2020 s’appuie sur un récolement des informations issues de la
        littérature existante (études ethnobotaniques, dictionnaires,
        occitans/languedociens des XVIIIe et XIXe siècles).
      </p>
      <p>
        La base de données documente à ce jour 250 plantes à usage. Ce corpus
        d’information synthétisé est directement relié à l’inventaire de la
        flore du Parc national. Il regroupe une ou des traductions de chaque
        référence taxonomique, des données localisées sur l’usage de la plante,
        ainsi que les sources bibliographiques
      </p>
      <p>
        En 2025, le Parc national a commandé à l’illustrateur naturaliste Julien
        Norwood une série de 20 illustrations pour mettre en valeur ce travail
        sous la forme d’une exposition, de cartes postales et d’un calendrier.
      </p>
      <p>
        La cueillette de plantes est une activité traditionnelle dans les
        Cévennes. Cependant, elle se pratique aujourd’hui dans le cadre
        réglementé du parc national afin de concilier préservation de la
        biodiversité et transmission des savoir-faire.
        <a
          href="https://www.cevennes-parcnational.fr/fr/le-parc-national-des-cevennes/la-reglementation-du-coeur/la-cueillette-et-le-prelevement-despeces"
          target="_blank"
          rel="noopener noreferrer"
          >Détail de la réglementation sur le site du Parc</a
        >
      </p>
      <p>
        <b
          >Attention: les propriétés décrites ici sont présentées à titre
          informatif. Elles sont basées sur des usages traditionnels mais
          l’utilisation des plantes, qu’elle soit alimentaire ou médicinale,
          doit se faire avec prudence. Ne consommez jamais une plante sans être
          sûr de son identification et de son usage approprié.</b
        >
      </p>
